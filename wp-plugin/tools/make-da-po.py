def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def unesc(s):
    return s.replace('\\"', '"').replace("\\\\", "\\")


def main():
    pot = (ROOT / "justsilver.pot").read_text(encoding="utf-8").split("\n")
    out, missing, i = [], [], 0
    header_done = False
    while i < len(pot):
        line = pot[i]
        if line.startswith('"Language-Team:') and not header_done:
            out.append(line)
            out.append('"Language: da_DK\\n"')
            out.append('"Plural-Forms: nplurals=2; plural=(n != 1);\\n"')
            header_done = True
            i += 1
            continue
        if line.startswith("msgid ") and line != 'msgid ""':
            mid = unesc(line[7:-1])
            j = i + 1
            plural = None
            while pot[j].startswith('"'):
                mid += unesc(pot[j][1:-1]); j += 1
            if pot[j].startswith("msgid_plural "):
                plural = unesc(pot[j][14:-1]); j += 1
            out.append(line)
